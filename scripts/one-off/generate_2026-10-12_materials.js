#!/usr/bin/env node
/**
 * Generates 2026-10-12_stumarcot_materials.sql — the one-off move of
 * Stumarcot's LIVE data onto the materials foundation (migrations 018/019).
 *
 * Every value comes from scripts/lib/materials.js and seed.js's recipe plan,
 * the same code the seed uses, so a seed run afterwards changes nothing
 * (verifiable in audit_log). Each step asserts its exact row count; any
 * mismatch aborts the whole script.
 *
 *   node scripts/one-off/generate_2026-10-12_materials.js
 */
const fs = require('fs');
const path = require('path');
const DOCS = path.join(__dirname, '..', '..', 'assets', 'docs', 'Stumarcot');
const read = f => JSON.parse(fs.readFileSync(path.join(DOCS, f), 'utf8'));
const productMaster   = read('product_master.json');
const ratiosMolds     = read('ratios_and_molds.json');
const materialsMaster = read('materials_master.json');

const { buildRecipePlan, canonColor } = require('../seed');
const {
  MATERIAL_UNITS, unitSymbolFor, resolveMaterialRef, isUnpigmented, buildMaterialPlan, productReviewFlags,
} = require('../lib/materials');

const BRANCHES = ['Mwanza', 'Dar es Salaam', 'Dodoma'];
// Live materials created by the original seed, by their old code
const LEGACY_REFS = {
  CEM: 'cement', CHIP: 'chipping', DUST: 'dust', KOK: 'kokoto', DAWA: 'dawa',
  MCH: 'mchanga_generic', RNG: 'rangi_generic',
};

const q = v => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const unit = sym => (sym == null ? 'NULL' : `(SELECT id FROM public.units WHERE organization_id = org AND symbol = ${q(sym)})`);
const mat = ref => `(SELECT id FROM public.materials WHERE organization_id = org AND material_id_ref = ${q(ref)})`;
const assert = (expected, label) =>
  `  GET DIAGNOSTICS n = ROW_COUNT;\n  IF n <> ${expected} THEN RAISE EXCEPTION '${label.replace(/'/g, "''")}: expected ${expected}, got %', n; END IF;\n`;

const plan = buildMaterialPlan(materialsMaster, BRANCHES);
const out = [];
const add = s => out.push(s);

add(`-- GENERATED by generate_2026-10-12_materials.js — do not edit by hand.
-- One-off: move Stumarcot's live data onto migrations 018/019. Run ONCE:
--   supabase db query --linked -f scripts/one-off/2026-10-12_stumarcot_materials.sql
DO $$
DECLARE
  org uuid;
  n   int;
BEGIN
  SELECT id INTO STRICT org FROM public.organizations WHERE legal_name = 'STUMARCOT CO LTD';
`);

// A. Give the 7 original materials their stable reference
add(`  -- A. Stable references for the original materials\n  UPDATE public.materials SET material_id_ref = CASE code\n` +
  Object.entries(LEGACY_REFS).map(([code, ref]) => `      WHEN ${q(code)} THEN ${q(ref)}`).join('\n') +
  `\n    END\n  WHERE organization_id = org AND material_id_ref IS NULL AND code IN (${Object.keys(LEGACY_REFS).map(q).join(', ')});\n` +
  assert(Object.keys(LEGACY_REFS).length, 'A: original materials referenced'));

// B. Units introduced by the materials master
add(`  -- B. Purchase/stock units from the materials master`);
for (const [symbol, u] of Object.entries(MATERIAL_UNITS)) {
  add(`  INSERT INTO public.units (organization_id, symbol, name, notes) VALUES (org, ${q(symbol)}, ${q(u.name)}, ${q(u.notes)})\n    ON CONFLICT (organization_id, symbol) DO NOTHING;`);
}

// C. Material categories
add(`\n  -- C. Material categories`);
plan.categories.forEach((name, i) => add(
  `  INSERT INTO public.material_categories (organization_id, name, display_order) VALUES (org, ${q(name)}, ${i + 1})\n    ON CONFLICT (organization_id, name) DO UPDATE SET display_order = EXCLUDED.display_order;`));

// D. Materials
add(`\n  -- D. Materials (13): global definition — no stock, no price`);
for (const m of plan.materials) {
  add(`  INSERT INTO public.materials (organization_id, material_id_ref, name, category_id, stock_unit_id, notes, status)
    VALUES (org, ${q(m.ref)}, ${q(m.name)},
            (SELECT id FROM public.material_categories WHERE organization_id = org AND name = ${q(m.category)}),
            ${unit(m.stockUnit)}, ${q(m.notes)}, 'active')
    ON CONFLICT (organization_id, material_id_ref) DO UPDATE
      SET name = EXCLUDED.name, category_id = EXCLUDED.category_id, stock_unit_id = EXCLUDED.stock_unit_id,
          notes = EXCLUDED.notes, status = 'active';`);
}

// E. Unit conversions
add(`\n  -- E. Unit conversions (1 unit = factor × stock unit)`);
for (const c of plan.conversions) {
  add(`  INSERT INTO public.material_unit_conversions (organization_id, material_id, unit_id, factor_to_stock_unit, notes)
    VALUES (org, ${mat(c.ref)}, ${unit(c.unit)}, ${c.factor}, ${q(c.notes)})
    ON CONFLICT (material_id, unit_id) DO UPDATE SET factor_to_stock_unit = EXCLUDED.factor_to_stock_unit, notes = EXCLUDED.notes;`);
}

// F. Per-branch sources
add(`\n  -- F. Per-branch sources (the file has Dodoma only)`);
for (const s of plan.sources) {
  add(`  INSERT INTO public.material_branch_sources (organization_id, material_id, branch_id, source_name, purchase_unit_id, is_primary, notes)
    VALUES (org, ${mat(s.ref)}, (SELECT id FROM public.branches WHERE organization_id = org AND name = ${q(s.branch)}),
            ${q(s.sourceName)}, ${unit(s.purchaseUnit)}, ${s.isPrimary}, ${q(s.notes)})
    ON CONFLICT (material_id, branch_id, source_name) DO UPDATE
      SET purchase_unit_id = EXCLUDED.purchase_unit_id, is_primary = EXCLUDED.is_primary, notes = EXCLUDED.notes;`);
}

// G. Recipe ingredients → specific materials (active recipe versions only)
add(`\n  -- G. Recipe ingredients: generic Mchanga/Rangi → specific materials; 'unit' → bucket`);
const categoryColours = Object.fromEntries(productMaster.categories.map(c =>
  [c.category_id, new Set((c.color_columns || []).map(canonColor))]));
for (const r of buildRecipePlan(productMaster, ratiosMolds)) {
  const colourName = canonColor(r.colorLabel);
  const isColour = categoryColours[r.categoryRef]?.has(colourName);
  const label = isColour ? colourName : r.colorLabel;
  const rv = `(SELECT rv.id FROM public.recipe_versions rv
      JOIN public.product_categories pc ON pc.id = rv.category_id
      LEFT JOIN public.color_palette cp ON cp.id = rv.color_id
      WHERE rv.organization_id = org AND pc.category_id_ref = ${q(r.categoryRef)} AND rv.version_number = 1
        AND rv.status = 'active' AND ${isColour ? `cp.name = ${q(colourName)}` : `rv.variant_label = ${q(r.colorLabel)}`})`;
  const tag = `${r.categoryRef}/${label}`;
  for (const comp of r.components) {
    const ctx = { colour: isColour ? colourName : null, sandRef: r.sandRef };
    const m = String(comp.material).toLowerCase();
    const legacy = m === 'mchanga' ? 'mchanga_generic' : m.startsWith('rangi') ? 'rangi_generic' : null;
    const unitSym = unitSymbolFor(comp.unit);
    if (isUnpigmented(comp, ctx)) {
      // White is unpigmented by design ('—' = recorded zero): remove the old
      // zero-quantity pigment placeholder line; no flag
      add(`  DELETE FROM public.recipe_items WHERE recipe_version_id = ${rv} AND material_id = ${mat(legacy)};\n` + assert(1, `G: remove zero pigment line from ${tag}`));
      continue;
    }
    const target = resolveMaterialRef(comp, ctx);
    if (!target) throw new Error(`No material for '${comp.material}' in ${tag}`);
    if (legacy) {
      add(`  UPDATE public.recipe_items SET material_id = ${mat(target)}, unit_id = ${unit(unitSym)}
    WHERE recipe_version_id = ${rv} AND material_id = ${mat(legacy)};\n` + assert(1, `G: ${comp.material} → ${target} in ${tag}`));
    } else {
      add(`  UPDATE public.recipe_items SET unit_id = ${unit(unitSym)}
    WHERE recipe_version_id = ${rv} AND material_id = ${mat(target)} AND unit_id IS DISTINCT FROM ${unit(unitSym)};
  SELECT count(*) INTO n FROM public.recipe_items WHERE recipe_version_id = ${rv} AND material_id = ${mat(target)};
  IF n <> 1 THEN RAISE EXCEPTION 'G: ${target} line in ${tag}: expected 1, got %', n; END IF;`);
    }
  }
}

// H. Retire the two generic materials (no active recipe uses them any more)
add(`\n  -- H. Retire the generic materials
  UPDATE public.materials m SET status = 'inactive'
  WHERE m.organization_id = org AND m.material_id_ref IN ('mchanga_generic', 'rangi_generic')
    AND NOT EXISTS (SELECT 1 FROM public.recipe_items ri JOIN public.recipe_versions rv ON rv.id = ri.recipe_version_id
                    WHERE ri.material_id = m.id AND rv.status = 'active');
` + assert(2, 'H: generic materials retired'));

// I. Branch managers no longer manage materials
add(`  -- I. materials.manage removed from branch_manager (build-plan 1a.1: org admins only)
  DELETE FROM public.role_permissions
  WHERE role_id = (SELECT id FROM public.roles WHERE organization_id = org AND name = 'branch_manager')
    AND permission_id = (SELECT id FROM public.permissions WHERE code = 'materials.manage');
` + assert(1, 'I: branch_manager materials.manage removed'));

// J. Review flags
add(`  -- J. Review flags from gaps the source files mark`);
const flag = (entityType, entityIdSql, code, reason) =>
  `  INSERT INTO public.review_flags (organization_id, entity_type, entity_id, reason_code, reason)
    SELECT org, ${q(entityType)}, e.id::text, ${q(code)}, ${q(reason)} FROM (SELECT ${entityIdSql} AS id) e
    WHERE e.id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.review_flags f WHERE f.organization_id = org
      AND f.entity_type = ${q(entityType)} AND f.entity_id = e.id::text AND f.reason_code = ${q(code)});
` + assert(1, `J: flag ${entityType} ${code}`);
for (const f of plan.flags) add(flag('material', mat(f.ref), f.code, f.reason));
for (const f of productReviewFlags(productMaster)) {
  add(flag('product', `(SELECT id FROM public.products WHERE organization_id = org AND product_id_ref = ${q(f.ref)})`, f.code, f.reason));
}

add(`END $$;`);

const file = path.join(__dirname, '2026-10-12_stumarcot_materials.sql');
fs.writeFileSync(file, out.join('\n') + '\n');
console.log(`wrote ${path.relative(process.cwd(), file)}: ${plan.materials.length} materials, ${plan.conversions.length} conversions, ` +
            `${plan.sources.length} sources, ${plan.flags.length + productReviewFlags(productMaster).length} flags`);
